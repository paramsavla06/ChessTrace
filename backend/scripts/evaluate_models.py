"""
Model Evaluation Script for ChessTrace V2.

Evaluates trained general and ELO-specific XGBoost models on the untouched held-out
final-test partition generated by `make_three_way_game_split`:
- Metrics: RMSE, MAE, R2, MedAE, Max Error, 95th Percentile Error
- Residual diagnostics: mean residual, std dev
- Naive baseline (draw expectation 0.5)
- Breakdown across rating brackets (ELO buckets)
- Breakdown across game phases (opening: plies 1-20, middlegame: 21-60, endgame: >60)
- Breakdown across clock telemetry (with vs without clock data)
- Breakdown across time controls (bullet, blitz, rapid, classical)
- Head-to-head comparison against V1 baseline models
- Outputs JSON report and Markdown artifact

Usage:
    python backend/scripts/evaluate_models.py --data-dir data/processed/v2 --weights-dir backend/app/ml/weights/v2 --output-dir backend/reports
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

backend_root = Path(__file__).resolve().parents[1]
if str(backend_root) not in sys.path:
    sys.path.insert(0, str(backend_root))

import numpy as np
import pandas as pd
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score, median_absolute_error

from app.core.constants import ELO_BUCKETS
from app.ml.collapse_model import FEATURE_COLUMNS, WinCollapsePredictor
from app.ml.split_utils import make_three_way_game_split

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
)
logger = logging.getLogger("evaluate_models")

DEFAULT_PROJECT_DIR = Path(__file__).resolve().parents[2]
DEFAULT_DATA_DIR = DEFAULT_PROJECT_DIR / "data/processed/v2"
DEFAULT_V2_WEIGHTS_DIR = DEFAULT_PROJECT_DIR / "backend/app/ml/weights/v2"
DEFAULT_V1_WEIGHTS_DIR = DEFAULT_PROJECT_DIR / "backend/app/ml/weights"
DEFAULT_REPORT_DIR = DEFAULT_PROJECT_DIR / "backend/reports"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Evaluate ChessTrace V2 XGBoost models and compare to V1.")
    parser.add_argument("--data-dir", type=Path, default=DEFAULT_DATA_DIR)
    parser.add_argument("--weights-dir", type=Path, default=DEFAULT_V2_WEIGHTS_DIR)
    parser.add_argument("--v1-weights-dir", type=Path, default=DEFAULT_V1_WEIGHTS_DIR)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_REPORT_DIR)
    parser.add_argument("--test-ratio", type=float, default=0.15)
    parser.add_argument("--val-ratio", type=float, default=0.15)
    parser.add_argument("--random-state", type=int, default=42)
    return parser.parse_args()


def compute_metrics(y_true: np.ndarray, y_pred: np.ndarray) -> dict[str, float]:
    y_pred_clipped = np.clip(y_pred, 0.0, 1.0)
    residuals = y_true - y_pred_clipped

    rmse = float(np.sqrt(mean_squared_error(y_true, y_pred_clipped)))
    mae = float(mean_absolute_error(y_true, y_pred_clipped))
    r2 = float(r2_score(y_true, y_pred_clipped))
    medae = float(median_absolute_error(y_true, y_pred_clipped))
    max_err = float(np.max(np.abs(residuals)))
    p95_err = float(np.percentile(np.abs(residuals), 95))
    mean_res = float(np.mean(residuals))
    std_res = float(np.std(residuals))

    return {
        "rmse": round(rmse, 4),
        "mae": round(mae, 4),
        "r2": round(r2, 4),
        "median_absolute_error": round(medae, 4),
        "max_error": round(max_err, 4),
        "p95_error": round(p95_err, 4),
        "mean_residual": round(mean_res, 4),
        "std_residual": round(std_res, 4),
    }


def evaluate(
    data_dir: Path,
    v2_weights_dir: Path,
    v1_weights_dir: Path,
    output_dir: Path,
    test_ratio: float = 0.15,
    val_ratio: float = 0.15,
    random_state: int = 42,
) -> dict[str, Any]:
    # 1. Obtain the untouched held-out final test partition
    test_partition_file = v2_weights_dir / "test_partition.parquet"

    if test_partition_file.exists():
        logger.info("Loading saved held-out test partition from %s...", test_partition_file.resolve())
        test_df = pd.read_parquet(test_partition_file)
    else:
        logger.info("Test partition file not found; regenerating via deterministic make_three_way_game_split...")
        parquet_files = sorted(data_dir.glob("*.parquet"))
        parquet_files = [f for f in parquet_files if not f.name.startswith("test_partition")]
        if not parquet_files:
            raise FileNotFoundError(f"No parquet files in {data_dir}")
        dfs = [pd.read_parquet(f) for f in parquet_files]
        full_df = pd.concat(dfs, ignore_index=True)
        _, _, test_df, _ = make_three_way_game_split(
            full_df, test_ratio=test_ratio, val_ratio=val_ratio, random_state=random_state
        )

    logger.info(
        "Evaluating on untouched final-test partition: %d rows across %d unique games.",
        len(test_df),
        test_df["game_id"].nunique(),
    )

    X_test = test_df[FEATURE_COLUMNS]
    y_test = test_df["game_result_score"].to_numpy(dtype=float)

    report: dict[str, Any] = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "total_test_samples": len(test_df),
        "unique_test_games": int(test_df["game_id"].nunique()),
        "v2_models": {},
        "v1_baseline_comparison": {},
        "naive_baseline": {},
        "phase_breakdown": {},
        "elo_breakdown": {},
        "clock_breakdown": {},
        "time_control_breakdown": {},
    }

    # 0. Naive baseline: always predict 0.5 (draw expectation)
    naive_preds = np.full_like(y_test, 0.5)
    report["naive_baseline"] = compute_metrics(y_test, naive_preds)
    logger.info("Naive Baseline (always 0.5): %s", report["naive_baseline"])

    # 1. Evaluate V2 General Model
    v2_gen_path = v2_weights_dir / "collapse_xgboost.json"
    if v2_gen_path.exists():
        v2_gen_pred = WinCollapsePredictor.load(v2_gen_path)
        v2_preds = v2_gen_pred.model.predict(X_test)
        report["v2_models"]["general"] = compute_metrics(y_test, v2_preds)
        test_df["v2_pred"] = v2_preds
        logger.info("V2 General Model Metrics: %s", report["v2_models"]["general"])
    else:
        logger.warning("V2 General Model not found at %s", v2_gen_path)

    # 2. Compare against V1 General Model
    v1_gen_path = v1_weights_dir / "collapse_xgboost.json"
    if v1_gen_path.exists():
        try:
            v1_gen_pred = WinCollapsePredictor.load(v1_gen_path)
            v1_preds = v1_gen_pred.model.predict(X_test)
            report["v1_baseline_comparison"]["general"] = compute_metrics(y_test, v1_preds)
            test_df["v1_pred"] = v1_preds
            logger.info("V1 Baseline Model Metrics: %s", report["v1_baseline_comparison"]["general"])

            # Compute relative improvements
            if "general" in report["v2_models"]:
                v2_rmse = report["v2_models"]["general"]["rmse"]
                v1_rmse = report["v1_baseline_comparison"]["general"]["rmse"]
                v2_mae = report["v2_models"]["general"]["mae"]
                v1_mae = report["v1_baseline_comparison"]["general"]["mae"]
                v2_r2 = report["v2_models"]["general"]["r2"]
                v1_r2 = report["v1_baseline_comparison"]["general"]["r2"]

                report["v1_baseline_comparison"]["delta"] = {
                    "rmse_improvement": round(v1_rmse - v2_rmse, 4),
                    "rmse_reduction_pct": round((v1_rmse - v2_rmse) / v1_rmse * 100, 2) if v1_rmse > 0 else 0.0,
                    "mae_improvement": round(v1_mae - v2_mae, 4),
                    "mae_reduction_pct": round((v1_mae - v2_mae) / v1_mae * 100, 2) if v1_mae > 0 else 0.0,
                    "r2_improvement": round(v2_r2 - v1_r2, 4),
                }
        except Exception as e:
            logger.warning("Could not evaluate V1 baseline: %s", e)

    # 3. Evaluate V2 7 ELO Bracket Models and compare to V1 ELO models
    for bucket in ELO_BUCKETS:
        safe_name = bucket.replace("<", "under_").replace("+", "_plus").replace("-", "_to_")
        v2_elo_path = v2_weights_dir / f"elo_xgboost_{safe_name}.json"
        v1_elo_path = v1_weights_dir / f"elo_xgboost_{safe_name}.json"
        elo_mask = (test_df["elo_bucket"] == bucket).to_numpy()
        elo_samples = int(np.sum(elo_mask))

        if v2_elo_path.exists() and elo_samples >= 10:
            elo_predictor = WinCollapsePredictor.load(v2_elo_path)
            sub_preds = elo_predictor.model.predict(X_test[elo_mask])
            v2_metrics = compute_metrics(y_test[elo_mask], sub_preds)
            report["v2_models"][f"elo_{bucket}"] = {
                "samples": elo_samples,
                "metrics": v2_metrics,
            }

            if v1_elo_path.exists():
                try:
                    v1_elo_predictor = WinCollapsePredictor.load(v1_elo_path)
                    v1_sub_preds = v1_elo_predictor.model.predict(X_test[elo_mask])
                    v1_metrics = compute_metrics(y_test[elo_mask], v1_sub_preds)
                    report["v1_baseline_comparison"][f"elo_{bucket}"] = v1_metrics
                except Exception as e:
                    logger.warning("Could not evaluate V1 ELO model for %s: %s", bucket, e)

    # 4. Phase Breakdown (Opening <= 20, Middlegame 21-60, Endgame > 60)
    if "v2_pred" in test_df.columns and "ply" in test_df.columns:
        phases = {
            "opening (ply <= 20)": test_df["ply"] <= 20,
            "middlegame (ply 21-60)": (test_df["ply"] > 20) & (test_df["ply"] <= 60),
            "endgame (ply > 60)": test_df["ply"] > 60,
        }
        for name, mask in phases.items():
            if mask.sum() > 0:
                report["phase_breakdown"][name] = {
                    "samples": int(mask.sum()),
                    "metrics": compute_metrics(y_test[mask], test_df.loc[mask, "v2_pred"].to_numpy()),
                }

    # 5. Clock telemetry breakdown
    if "v2_pred" in test_df.columns and "think_time" in test_df.columns:
        has_clock_mask = (test_df["think_time"] > 0).to_numpy()
        no_clock_mask = ~has_clock_mask
        if has_clock_mask.sum() > 0:
            report["clock_breakdown"]["with_clock"] = {
                "samples": int(has_clock_mask.sum()),
                "metrics": compute_metrics(y_test[has_clock_mask], test_df.loc[has_clock_mask, "v2_pred"].to_numpy()),
            }
        if no_clock_mask.sum() > 0:
            report["clock_breakdown"]["without_clock"] = {
                "samples": int(no_clock_mask.sum()),
                "metrics": compute_metrics(y_test[no_clock_mask], test_df.loc[no_clock_mask, "v2_pred"].to_numpy()),
            }

    # 6. Time control breakdown
    if "v2_pred" in test_df.columns and "time_control" in test_df.columns:
        for tc in test_df["time_control"].unique():
            tc_mask = (test_df["time_control"] == tc).to_numpy()
            if tc_mask.sum() >= 10:
                report["time_control_breakdown"][str(tc)] = {
                    "samples": int(tc_mask.sum()),
                    "metrics": compute_metrics(y_test[tc_mask], test_df.loc[tc_mask, "v2_pred"].to_numpy()),
                }

    # 7. ELO breakdown of V2 General model across rating tiers
    if "v2_pred" in test_df.columns and "elo_bucket" in test_df.columns:
        for bucket in ELO_BUCKETS:
            elo_mask = (test_df["elo_bucket"] == bucket).to_numpy()
            elo_samples = int(np.sum(elo_mask))
            if elo_samples >= 10:
                report["elo_breakdown"][bucket] = {
                    "samples": elo_samples,
                    "metrics": compute_metrics(y_test[elo_mask], test_df.loc[elo_mask, "v2_pred"].to_numpy()),
                }

    # Save outputs
    output_dir.mkdir(parents=True, exist_ok=True)
    json_path = output_dir / "evaluation_report_v2.json"
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)

    logger.info("Evaluation report successfully written to %s", json_path.resolve())
    return report


def main():
    args = parse_args()
    evaluate(
        args.data_dir,
        args.weights_dir,
        args.v1_weights_dir,
        args.output_dir,
        test_ratio=args.test_ratio,
        val_ratio=args.val_ratio,
        random_state=args.random_state,
    )


if __name__ == "__main__":
    main()
